# Trains the shipped pre-trained tables on ALL the data in validation/data and
# writes base44/shared/pretrainedTables.ts. (The tested tables in pretrain.py
# hold out each family's test period; the shipped ones use everything, since
# live use is on data that comes after all of it.)
import numpy as np, json, os
from pretrain import load_families, train_tables, FAMILIES, HERE, CHUNK, K0
F=load_families()
T={f:train_tables(F[f]['train']+[r for _,r in F[f]['test']]) for f in FAMILIES}
fmt=lambda v: '['+', '.join(f'{x:.5f}' for x in v)+']'
out=['''// ===========================================================================
// Pre-trained state tables. GENERATED by validation/export_tables.py — do not
// edit by hand.
//
// For each engine state, how far the outcome has run from a series' own base
// rate, learned on three families of real data. They are a starting prior
// only: a series' own evidence outgrows them, and a family that does not fit
// a series is weighted out by that series' own outcomes.
//
// Training steps (direction / size):
''']
for f in FAMILIES: out.append(f"//   {f:8s} {T[f]['n_dir']:>7,} / {T[f]['n_size']:>7,}\n")
out.append(f"// Young-series training: each series cut into chunks of {CHUNK} steps; shrinkage k0 = {K0}.\n// ===========================================================================\n\n")
out.append("export const PRETRAINED_FAMILIES = ['markets', 'weather', 'racing'] as const;\n\n")
out.append("/** 128 direction states: deviation of P(up) from the base rate. */\nexport const PRETRAINED_DIRECTION: number[][] = [\n"+',\n'.join('  '+fmt(T[f]['dir']) for f in FAMILIES)+",\n];\n\n")
out.append("/** 64 size states: deviation of P(larger-than-usual move) from the base rate. */\nexport const PRETRAINED_SIZE: number[][] = [\n"+',\n'.join('  '+fmt(T[f]['size']) for f in FAMILIES)+",\n];\n")
open(os.path.join(HERE,'..','base44','shared','pretrainedTables.ts'),'w').write(''.join(out))
json.dump({f:{'dir':[round(float(x),5) for x in T[f]['dir']],'size':[round(float(x),5) for x in T[f]['size']]} for f in FAMILIES},open(os.path.join(HERE,'shipped_tables.json'),'w'))
print({f:(T[f]['n_dir'],T[f]['n_size']) for f in FAMILIES})
