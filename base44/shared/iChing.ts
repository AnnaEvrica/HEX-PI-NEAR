export function iChingForState(state: number) {
  const bottomToTop = state.toString(2).padStart(6, '0');
  const hexagram = KING_WEN_BY_BOTTOM_TO_TOP[bottomToTop];
  if (!hexagram) throw new Error(`Missing I Ching mapping for state ${state}`);
  return {
    ...hexagram,
    glyph: String.fromCodePoint(0x4dc0 + hexagram.king_wen - 1),
    engine_state: state,
    engine_bits_bottom_to_top: bottomToTop,
    fuxi_index: parseInt(bottomToTop.split('').reverse().join(''), 2),
    lines_bottom_to_top: bottomToTop.split('').map((bit) => bit === '1' ? '⚊' : '⚋'),
  };
}