// Writes docs/PROMPT.md from the code, so the document cannot drift from what
// runs. The smoke test fails when the file is out of date.
//   node tests/backend-smoke/build.mjs && node tests/render-prompt.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { load, call, sub, synthPrompt } from './backend-smoke/harness.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));

// Lines that change with the clock are replaced so the file is stable.
const steady = (p) => p
  .replace(/time: it is .*? where they are \(.*?\)\./, 'time: it is [their local date and time] where they are ([their timezone]).')
  .replace(/Today is [^.\n]*\./, 'Today is [today\'s date].');

export async function renderPromptDoc() {
  const out = path.join(here, 'backend-smoke', 'out', 'persona.mjs');
  await build({ entryPoints: [path.join(here, '../base44/shared/persona.ts')], bundle: true, format: 'esm', outfile: out, logLevel: 'error' });
  const P = await import(`${out}?${Math.random()}`);
  const { ENGINE_VERSION } = await import(`${path.join(here, 'backend-smoke', 'out', 'version.mjs')}?${Math.random()}`).catch(() => ({ ENGINE_VERSION: '' }));
  const think = await load('think');
  await call(think, sub, { message: "what's your read on BTC right now?" });
  const market = steady(synthPrompt());
  await call(think, sub, { message: 'hey' });
  const casual = steady(synthPrompt());
  const block = (t) => '```text\n' + t.trim() + '\n```';
  return `# HEX [PI] — the prompt

**Generated from the code. Do not edit this file.** Change \`base44/shared/persona.ts\`
or \`base44/functions/think/entry.ts\` and run \`node tests/render-prompt.mjs\`.
The smoke test fails when this file does not match what the code builds.

One language model writes every reply: Claude. The web model only retrieves.
Probability and statistics only: no confidence or conviction wording.

## The three lines every function shares

${block([P.IDENTITY_LINE, P.CONFIDENTIALITY_LINE, P.STATISTICS_LINE].join('\n\n'))}

## Full persona (substantive turns)

${block(P.buildPersona())}

## Refresher (short casual turns)

${block(P.buildPersonaRefresher())}

## A complete prompt as sent: a market question

The message was "what's your read on BTC right now?", run on the stored BTC
bars used by the tests. The date and time lines are replaced with placeholders.

${block(market)}

## A complete prompt as sent: a greeting

${block(casual)}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const doc = await renderPromptDoc();
  fs.mkdirSync(path.join(here, '../docs'), { recursive: true });
  fs.writeFileSync(path.join(here, '../docs/PROMPT.md'), doc);
  console.log(`docs/PROMPT.md written (${doc.length} characters)`);
  process.exit(0);
}
